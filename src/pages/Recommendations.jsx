import { useState } from 'react';
import { Link } from 'react-router-dom';
import halls from '../data/halls';

function Recommendations() {
  const [budget, setBudget] = useState(60000);
  const [guests, setGuests] = useState(100);
  const [location, setLocation] = useState('Any');
  const [showResults, setShowResults] = useState(false);

  const recommendations = halls
    .map((hall) => {
      const price = Number(hall.price);
      const capacity = Number(hall.capacity);
      const report = hall.realityReport || {};

      const fitsBudget = price <= Number(budget);
      const fitsGuests = capacity >= Number(guests);

      const score = Math.round(
        (Number(report.crowdComfort || 0) * 0.3) +
        (Number(report.trueValue || 0) * 0.3) +
        ((Number(hall.rating || 0) / 5) * 100 * 0.4)
      );

      return {
        ...hall,
        score,
        fitsBudget,
        fitsGuests,
      };
    })
    .filter((hall) =>
      location === 'Any' ||
      hall.location.toLowerCase() === location.toLowerCase()
    )
    .sort((a, b) => {
      const aFits = a.fitsBudget && a.fitsGuests;
      const bFits = b.fitsBudget && b.fitsGuests;

      if (aFits !== bFits) return aFits ? -1 : 1;
      return b.score - a.score;
    });

  return (
    <div className="page-container">
      <div className="halls-heading">
        <p className="halls-eyebrow">✦ SMART VENUE FINDER</p>
        <h1>Find Your Perfect Party Hall</h1>
        <p>Tell us your requirements and discover suitable venues.</p>
      </div>

      <section className="recommendation-form">
        <h2>Your Event Requirements</h2>

        <label htmlFor="budget">Maximum budget (₹)</label>
        <input
          id="budget"
          type="number"
          min="1"
          value={budget}
          onChange={(e) => setBudget(e.target.value)}
        />

        <label htmlFor="guests">Number of guests</label>
        <input
          id="guests"
          type="number"
          min="1"
          value={guests}
          onChange={(e) => setGuests(e.target.value)}
        />

        <label htmlFor="location">Location</label>
        <select
          id="location"
          value={location}
          onChange={(e) => setLocation(e.target.value)}
        >
          <option value="Any">Any location</option>
          <option value="Chennai">Chennai</option>
        </select>

        <button
          type="button"
          className="btn-primary recommendation-submit"
          disabled={Number(budget) <= 0 || Number(guests) <= 0}
          onClick={() => setShowResults(true)}
        >
          Find My Best Halls
        </button>
      </section>

      {showResults && (
        <section className="recommendation-results">
          <h2>Your Recommendations</h2>

          {recommendations.length === 0 ? (
            <p>No halls found for this location.</p>
          ) : (
            recommendations.map((hall, index) => (
              <article
                key={hall.id}
                className="recommendation-card"
              >
                <img
                  src={hall.image}
                  alt={hall.name}
                  className="recommendation-image"
                />

                <div className="recommendation-card-body">
                  {index === 0 && <strong>✦ Top Match</strong>}

                  <h3>{hall.name}</h3>
                  <p>Location: {hall.location}</p>
                  <p>
                    Price: ₹
                    {Number(hall.price).toLocaleString('en-IN')}
                  </p>
                  <p>Capacity: {hall.capacity} guests</p>
                  <p>Rating: ★ {hall.rating}/5</p>
                  <p>Match score: {hall.score}%</p>

                  {!hall.fitsBudget && (
                    <p>This hall exceeds your budget.</p>
                  )}

                  {!hall.fitsGuests && (
                    <p>This hall may be too small for your guest list.</p>
                  )}

                  <Link
                    to={`/halls/${hall.id}`}
                    className="btn-secondary recommendation-details"
                  >
                    View Hall Details →
                  </Link>
                </div>
              </article>
            ))
          )}

          <p className="compare-note">
            Recommendations use a rule-based calculation and the
            project's sample venue data. They are not generated by
            a trained AI model.
          </p>
        </section>
      )}
    </div>
  );
}

export default Recommendations;